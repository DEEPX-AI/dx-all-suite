"""README.md for the python and cpp dirs, and MODELS.md (spec §4)."""
import json

from dx_modelzoo.core import model_card as mc
from dx_modelzoo.core.model_card_labels import LABELS, clean_labels, t
from dx_modelzoo.core.model_card_md import render_index, render_markdown
from tests.dx_modelzoo.test_model_card import MODEL, ROW, app  # noqa: F401  (fixture)


def _card(app):
    card = mc.build_card(MODEL, ROW, app, asof="2026-10-13")
    card["has_image"] = True
    return card


def test_python_readme(app):
    md = render_markdown(_card(app), "python")
    assert md.startswith("<!-- Generated by DX AI Studio")
    assert "# YOLOv5-m-face" in md and "![YOLOv5-m-face output](result.webp)" in md
    assert md.index("python src/python_example") < md.index("./bin/yolov5-m-face_640x640_sync")
    assert "| Q-Lite | 95.57 (±0.00) | 94.14 (+0.01) | 86.33 (−0.01) |" in md
    assert "Q-Pro is 7.57 points below Raw on AP(Easy)." in md
    assert "[C++ version of this example](../../../../cpp_example/face_detection/yolov5_face/yolov5-m-face_640x640/)" in md
    assert "[model.html](model.html)" in md
    assert "devops.dpx.ai" not in md
    assert "GPL-3.0 (GNU GPL v3) · © deepcam-cn. Check the upstream license" in md    # no "— —" without a source
    assert "\n\n\n" not in md                                                         # no boards: one blank line
    assert "(as of 2026-10-13)" in md and "Board measurements" not in md


def test_source_link_and_license_text(app):
    card = _card(app)
    card["source"] = "https://github.com/deepcam-cn/yolov5-face"
    md = render_markdown(card, "python")
    assert ("[deepcam-cn/yolov5-face](https://github.com/deepcam-cn/yolov5-face) — GPL-3.0 (GNU GPL v3) · "
            "© deepcam-cn.") in md


def test_empty_files_and_downloads(app):
    card = _card(app)
    card["files"]["python"] = []
    card["downloads"] = {"onnx": None, "tiers": []}
    md = render_markdown(card, "python")
    assert "No example files in this checkout." in md and "| File | What it is |" not in md
    assert "No public downloads." in md and "| Artifact | Compiler | Files |" not in md


def test_no_date_and_a_board_month_in_the_footer(app):
    card = _card(app)
    card["asof"] = None
    card["boards"] = {"rows": [{"board": "DX-M1 · Raspberry Pi 5", "throughput_fps": 179.6, "single_fps": 46.4,
                                "latency_ms": 21.5}], "measured": "July 2026"}
    md = render_markdown(card, "python")
    assert "Generated from the DX Model Zoo publish table. Board measurements: DX AI Studio Benchmark, July 2026." in md
    assert "as of" not in md and "None" not in md
    card["boards"]["measured"] = None
    md = render_markdown(card, "python")
    assert "DX AI Studio Benchmark, DX-RT without ORT." in md and "None" not in md and "Board measurements" not in md


def test_unpublished_note_in_performance(app):
    card = _card(app)
    card["published"] = False
    md = render_markdown(card, "python")
    perf = md[md.index("## Performance"):md.index("## Model")]
    assert "Numbers from the DX AI Studio catalog; this model is not in the DX Model Zoo publish table." in perf
    md = render_markdown(_card(app), "python")
    assert "publish table" not in md[md.index("## Performance"):md.index("## Model")]


def test_no_cpp_dir_no_cpp_link(app):
    card = _card(app)
    card["has_cpp"] = False
    assert "C++ version of this example" not in render_markdown(card, "python")
    assert "[C++]" not in render_index([card], "2026-10-13")


def test_cpp_readme_points_at_the_python_dir(app):
    md = render_markdown(_card(app), "cpp")
    py = "../../../../python_example/face_detection/yolov5_face/yolov5-m-face_640x640/"
    assert f"![YOLOv5-m-face output]({py}result.webp)" in md
    assert f"({py}model.html)" in md
    assert md.index("./bin/yolov5-m-face_640x640_sync") < md.index("python src/python_example")


def test_missing_fps_shows_the_measure_command(app):
    card = _card(app)
    card["fps"] = None
    assert "Throughput for this model is not published yet." in render_markdown(card, "python")
    assert "--loop 100 --no-display" in render_markdown(card, "python")


def test_index_links_every_card(app):
    md = render_index([_card(app)], "2026-10-13")
    assert "## Face Detection" in md
    assert "[Python](src/python_example/face_detection/yolov5_face/yolov5-m-face_640x640/README.md)" in md
    assert "[C++](src/cpp_example/face_detection/yolov5_face/yolov5-m-face_640x640/README.md)" in md


def test_labels():
    assert "Quick start" in LABELS
    assert t({}, "Download {tier} DXNN", tier="Q-Lite") == "Download Q-Lite DXNN"
    assert t({"Download {tier} DXNN": "{tier} DXNN 다운로드"}, "Download {tier} DXNN", tier="Q-Lite") == "Q-Lite DXNN 다운로드"
    assert t({"Download {tier} DXNN": "broken {nope}"}, "Download {tier} DXNN", tier="Q-Lite") == "Download Q-Lite DXNN"
    assert clean_labels({"Quick start": "빠른 시작", "evil": "x", "Copy": 3, "Model": "y" * 999}) == {"Quick start": "빠른 시작"}
