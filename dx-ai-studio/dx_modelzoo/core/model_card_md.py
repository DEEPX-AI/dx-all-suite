"""Model card → README.md (python or cpp dir) and the dx_app-wide MODELS.md. English only.

A dx_app example card carries no benchmark numbers (FPS, FPS/W, board measurements): they are Studio Benchmark
data and do not describe the example; accuracy stays.

Contract: tests/dx_modelzoo/test_model_card_md.py
"""
from __future__ import annotations

from dx_modelzoo.core.model_card import commands, fmt_delta, fmt_input, fmt_num, rel_dir
from dx_modelzoo.core.model_card_labels import CATALOG_NUMBERS, generated_note, lede

HEADER = ("<!-- Generated by DX AI Studio (python -m dx_modelzoo.tools.export_dx_app_cards). "
          "Do not edit by hand. -->\n")


def _cell(text):
    return str(text).replace("|", "\\|")


def _accuracy(card):
    acc = card["accuracy"]
    if not acc["rows"]:
        return "No accuracy published.\n"
    out = ["| Quantization | " + " | ".join(_cell(m) for m in acc["metrics"]) + " |",
           "|---|" + "---:|" * len(acc["metrics"])]
    for row in acc["rows"]:
        cells = []
        for c in row["cells"]:
            value = fmt_num(c["value"])
            cells.append(value if c["delta"] is None else f"{value} ({fmt_delta(c['delta'])})")
        out.append(f"| {row['label']} | " + " | ".join(cells) + " |")
    text = "\n".join(out) + "\n"
    if card["dataset"] and any(c["delta"] is not None for r in acc["rows"] for c in r["cells"]):
        text += f"\n{card['dataset']} · difference vs Raw in brackets.\n"
    for w in acc["warnings"]:
        text += f"\n> **Note:** {w['tier']} is {w['drop']:.2f} points below Raw on {w['metric']}.\n"
    return text


def render_markdown(card, lang):
    """lang: "python" (README next to model.html) or "cpp" (links back to the python dir)."""
    py, cpp = card["paths"]["python"], card["paths"]["cpp"]
    to_py = "" if lang == "python" else rel_dir(cpp, py)
    other = (rel_dir(py, cpp) if card["has_cpp"] else None) if lang == "python" else rel_dir(cpp, py)
    other_label = "C++ version of this example" if lang == "python" else "Python version of this example"
    cmds = commands(card)
    run = [("Python", cmds["python"]), ("C++", cmds["cpp"])]
    if lang == "cpp":
        run.reverse()
    tiers = card["downloads"]["tiers"]
    facts = [("Input", fmt_input(card["input"])), ("Dataset", card["dataset"]), ("License", card["license"]),
             ("Quantization", ", ".join(t["label"] for t in tiers))]
    lines = [HEADER, f"# {card['name']}", "",
             f"{card['task_label']} · `{card['variant']}` · DX-APP {'Python' if lang == 'python' else 'C++'} example", "",
             lede(card), "",
             " · ".join(f"**{k}** {v}" for k, v in facts if v), ""]
    if not card["published"]:
        lines += ["> Not published in DX Model Zoo.", ""]
    if card["has_image"]:
        lines += [f"![{card['name']} output]({to_py}result.webp)", ""]
    lines += [f"Full card with copy buttons and dark/light theme (open it in a browser; GitHub shows its source): "
              f"[model.html]({to_py}model.html)", "",
              "## Quick start", "", "Run from the dx_app root after `./install.sh` and `./build.sh`.", "",
              "```bash", cmds["get"], "```", ""]
    for title, cmd in run:
        lines += [f"**{title}**", "", "```bash", cmd, "```", ""]
    lines += ["## Accuracy", ""]
    if not card["published"]:
        lines += [CATALOG_NUMBERS, ""]
    lines += [_accuracy(card)]
    lines += ["## Model", "", "| | |", "|---|---|"]
    for key, value in (("Task", card["task_label"]), ("Dataset", card["dataset"]),
                       ("Metric", " · ".join(card["accuracy"]["metrics"])), ("Input", fmt_input(card["input"])),
                       ("Parameters", f"{fmt_num(card['params'])} M" if card["params"] is not None else None),
                       ("Operations", f"{fmt_num(card['ops'])} GOPs" if card["ops"] is not None else None),
                       ("Family", card["family"])):
        if value:
            lines.append(f"| {key} | {_cell(value)} |")
    lines += ["", "## Downloads", ""]
    manifest = card["downloads"].get("manifest")
    if card["downloads"]["onnx"] or tiers or manifest:
        lines += ["| Artifact | Compiler | Files |", "|---|---|---|"]
        if card["downloads"]["onnx"]:
            lines.append(f"| ONNX | — | [ONNX]({card['downloads']['onnx']}) |")
        for t in tiers:
            files = f"[DXNN]({t['dxnn']})" + (f" · [JSON]({t['json']})" if t["json"] else "")
            lines.append(f"| {t['label']} | DX-COM {t['compiler'] or '—'} | {files} |")
        if manifest:
            lines.append(f"| DXNN (dx_app manifest) | DX-COM {manifest['compiler'] or '—'} | [DXNN]({manifest['dxnn']}) |")
    else:
        lines.append("No public downloads.")
    lines += ["", "## Files in this example", ""]
    if card["files"][lang]:
        lines += ["| File | What it is |", "|---|---|"]
        lines += [f"| `{f['name']}` | {f['role']} |" for f in card["files"][lang]]
    else:
        lines.append("No example files in this checkout.")
    if other:
        lines += ["", f"[{other_label}]({other})"]
    lines += ["", "## Source & License", ""]
    license_ = card["license"] or card["license_text"] or "—"
    if card["license"] and card["license_text"] and card["license_text"] != card["license"]:
        license_ += f" ({card['license_text']})"
    if card["source"]:
        license_ = f"[{card['source'].replace('https://github.com/', '')}]({card['source']}) — {license_}"
    owner = f" · © {card['copyright']}" if card["copyright"] else ""
    footer = generated_note(card)
    lines += [f"{license_}{owner}. Check the upstream license before commercial use.", "",
              "Compile it yourself: DX-COM in dx-compiler, or DX AI Studio → Compiler.", "", "---", "",
              f"<sub>{footer} Open this model in DX AI Studio → Model Zoo for live inference and the model graph.</sub>",
              ""]
    return "\n".join(lines)


def _download(card):
    """MODELS.md's download cell: the first published tier's DXNN, else the dx_app manifest's, else a dash."""
    tiers, manifest = card["downloads"]["tiers"], card["downloads"].get("manifest")
    if tiers:
        return f"[{tiers[0]['label']} DXNN]({tiers[0]['dxnn']})"
    if manifest:
        return f"[DXNN]({manifest['dxnn']})"
    return "—"


def render_index(cards, asof):
    when = f" (as of {asof})" if asof else ""
    lines = [HEADER, "# DX-APP models", "",
             f"{len(cards)} examples, generated from the DX Model Zoo publish table{when}. "
             "Each row links the Python and C++ example cards.", ""]
    by_task = {}
    for card in cards:
        by_task.setdefault(card["task_label"], []).append(card)
    for task in sorted(by_task):
        lines += [f"## {task}", "", "| Model | Input | Accuracy (Q-Lite) | Download | Examples |",
                  "|---|---|---:|---|---|"]
        for card in sorted(by_task[task], key=lambda c: c["name"].lower()):
            qlite = next((r for r in card["accuracy"]["rows"] if r["tier"] == "qlite"), None)
            acc = "—"
            if qlite and qlite["cells"] and qlite["cells"][0]["value"] is not None:
                acc = f"{fmt_num(qlite['cells'][0]['value'])} {card['accuracy']['metrics'][0]}"
            links = f"[Python]({card['paths']['python']}/README.md)"
            if card["has_cpp"]:
                links += f" · [C++]({card['paths']['cpp']}/README.md)"
            lines.append(f"| {_cell(card['name'])} (`{card['variant']}`) | {fmt_input(card['input'])} | {_cell(acc)} | "
                         f"{_download(card)} | {links} |")
        lines.append("")
    return "\n".join(lines)
